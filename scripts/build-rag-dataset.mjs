import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const knowledgeDir = path.join(root, 'knowledge');
const manifest = JSON.parse(fs.readFileSync(path.join(knowledgeDir, 'manifest.json'), 'utf8'));

function slugId(filename) {
  return 'seed_' + filename.replace(/\.md$/, '').replace(/[^a-z0-9]+/gi, '_');
}

function titleFromMarkdown(content, fallback) {
  const m = content.match(/^#\s+(.+)$/m);
  return (m ? m[1].trim() : fallback).slice(0, 120);
}

const records = [];
for (const file of manifest.documents) {
  const abs = path.join(knowledgeDir, file);
  const content = fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n').trim() + '\n';
  records.push({
    id: slugId(file),
    title: titleFromMarkdown(content, file),
    path: 'knowledge/' + file,
    content,
  });
}

const jsonl = records.map((r) => JSON.stringify(r)).join('\n') + '\n';
fs.writeFileSync(path.join(knowledgeDir, 'dataset.jsonl'), jsonl);

function tsString(s) {
  return JSON.stringify(s);
}

const ts =
  '/** Generated by scripts/build-rag-dataset.mjs — do not edit by hand. */\n' +
  'export const KNOWLEDGE_DATASET_VERSION = ' +
  tsString(manifest.version) +
  ';\n' +
  'export const KNOWLEDGE_DATASET_REFRESHED = ' +
  tsString(manifest.refreshed) +
  ';\n\n' +
  'export interface KnowledgeRecord {\n' +
  '  id: string;\n' +
  '  title: string;\n' +
  '  path: string;\n' +
  '  content: string;\n' +
  '}\n\n' +
  'export const KNOWLEDGE_DATASET: KnowledgeRecord[] = ' +
  JSON.stringify(records, null, 2) +
  ';\n';

fs.writeFileSync(path.join(root, 'services/ragDataset.ts'), ts);
console.log(
  'Wrote ' +
    records.length +
    ' docs, version ' +
    manifest.version +
    ' → knowledge/dataset.jsonl + services/ragDataset.ts'
);
