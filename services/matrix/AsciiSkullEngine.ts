export interface MaskGrid {
  rows: number;
  cols: number;
  occupied: boolean[][];
  occupiedCols: boolean[];
}

export class AsciiSkullEngine {
  /**
   * Selects the ideal skull art matrix based on target pixel width & character size
   */
  public static getSkullLines(widthPx: number): string[] {
    return widthPx < 640 ? SKULL_COMPACT : SKULL_STANDARD;
  }

  /** Canonical occupancy grid copied from components/chat/matrix.sh */
  public static getMaskGrid(lines: string[] = ABLITERATED_SHAPE_MASK): MaskGrid {
    const rows = lines.length;
    let cols = 0;
    for (const line of lines) {
      if (line.length > cols) cols = line.length;
    }
    const occupied: boolean[][] = [];
    const occupiedCols = new Array(cols).fill(false);
    for (let r = 0; r < rows; r++) {
      const line = lines[r] || '';
      const row: boolean[] = new Array(cols);
      for (let c = 0; c < cols; c++) {
        const on = line[c] !== undefined && line[c] !== ' ';
        row[c] = on;
        if (on) occupiedCols[c] = true;
      }
      occupied.push(row);
    }
    return { rows, cols, occupied, occupiedCols };
  }

  /**
   * Generates cell representations with tier shading (1 to 4)
   */
  public static parseSkull(
    lines: string[],
    offsetX: number,
    offsetY: number
  ): SkullCell[] {
    const cells: SkullCell[] = [];
    for (let r = 0; r < lines.length; r++) {
      const line = lines[r];
      for (let c = 0; c < line.length; c++) {
        const ch = line[c];
        if (ch && ch !== ' ') {
          let tier: 1 | 2 | 3 | 4 = 2;
          if (ch === ':' || ch === '.' || ch === "'") {
            tier = 3;
          } else if (ch === '|' || ch === '=' || ch === '#') {
            tier = 4;
          } else if (ch === '"' || ch === '-' || ch === '`') {
            tier = 1;
          }
          cells.push({
            char: ch,
            tier,
            x: offsetX + c,
            y: offsetY + r,
          });
        }
      }
    }
    return cells;
  }
}

