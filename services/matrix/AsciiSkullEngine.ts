export interface MaskGrid {
  rows: number;
  cols: number;
  occupied: boolean[][];
  occupiedCols: boolean[];
  chars: string[][];
  edge: boolean[][];
}

export class AsciiSkullEngine {
  /**
   * Selects the ideal skull art matrix based on target pixel width & character size
   */
  public static getSkullLines(widthPx: number): string[] {
    return widthPx < 640 ? SKULL_COMPACT : SKULL_STANDARD;
  }

  public static charTier(ch: string): 1 | 2 | 3 | 4 {
    if (!ch || ch === ' ') return 1;
    if ('@#%█'.includes(ch)) return 4;
    if ('=*+▓'.includes(ch)) return 3;
    if (':.|▒/\\'.includes(ch)) return 2;
    return 1;
  }

  /** Canonical occupancy grid copied from components/chat/matrix.sh */
  public static getMaskGrid(lines?: string[]): MaskGrid {
    const src = lines ?? ABLITERATED_SHAPE_MASK;
    const rows = src.length;
    let cols = 0;
    for (const line of src) {
      if (line.length > cols) cols = line.length;
    }
    const occupied: boolean[][] = [];
    const chars: string[][] = [];
    const occupiedCols = new Array(cols).fill(false);
    for (let r = 0; r < rows; r++) {
      const line = src[r] || '';
      const row: boolean[] = new Array(cols);
      const rowChars: string[] = new Array(cols);
      for (let c = 0; c < cols; c++) {
        const ch = line[c] && line[c] !== ' ' ? line[c] : '';
        row[c] = ch !== '';
        rowChars[c] = ch;
        if (ch) occupiedCols[c] = true;
      }
      occupied.push(row);
      chars.push(rowChars);
    }
    const edge: boolean[][] = [];
    for (let r = 0; r < rows; r++) {
      const row: boolean[] = new Array(cols);
      for (let c = 0; c < cols; c++) {
        if (!occupied[r][c]) {
          row[c] = false;
          continue;
        }
        row[c] =
          !occupied[r - 1]?.[c] ||
          !occupied[r + 1]?.[c] ||
          !occupied[r][c - 1] ||
          !occupied[r][c + 1];
      }
      edge.push(row);
    }
    return { rows, cols, occupied, occupiedCols, chars, edge };
  }

  /**
   * Generates cell representations with tier shading (1 to 4)
   */
  public static parseSkull(
    lines: string[],
    offsetX: number,
    offsetY: number
  ): SkullCell[] {
    const cells: SkullCell[] = [];
    for (let r = 0; r < lines.length; r++) {
      const line = lines[r];
      for (let c = 0; c < line.length; c++) {
        const ch = line[c];
        if (ch && ch !== ' ') {
          const tier = AsciiSkullEngine.charTier(ch);
          cells.push({
            char: ch,
            tier,
            x: offsetX + c,
            y: offsetY + r,
          });
        }
      }
    }
    return cells;
  }
}

